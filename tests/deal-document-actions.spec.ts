test("review preserves both document IDs, saves before completion, and never confirms a mismatched Deal link", async ({ page }) => {
  const panel = await openDocuments(page)
  await panel.getByRole("button", { name: "기타 서류 3건", exact: true }).click()
  await panel.getByRole("button", { name: /Inspection_Report_0706.pdf/ }).click()
  await panel.getByRole("button", { name: "검사성적서 문서 작업" }).click()
  await page.getByRole("menuitem", { name: "검토 화면 열기" }).click()
  const complete = page.getByRole("button", { name: "검토 완료 · 거래로 돌아가기", exact: true })
  await expect(complete).toBeDisabled()
  const missing = page.locator('[data-upload-field="document_number"] input')
  await missing.fill("QC-2026-0706")
  await missing.press("Tab")
  await expect(complete).toBeEnabled()
  await complete.click()
  await expect(page).toHaveURL(new RegExp(`/erp/deals/${source}$`))
  const saved = await page.evaluate(key => JSON.parse(localStorage.getItem(key)!), storageKey)
  expect(saved.documents[`demo-trade-doc:${source}:QC`]).toMatchObject({ state: "ready", dealId: source })
  expect(saved.history.map((entry: { action: string }) => entry.action)).toEqual(["원문 검토 완료"])
  await page.goto(`/erp/documents/upload/${encodeURIComponent(`demo-erp-doc:${source}:QC`)}/review?from=deal&dealId=${target}&tradeDocId=${encodeURIComponent(`demo-trade-doc:${source}:QC`)}`)
  await expect(page.getByRole("heading", { name: "검토할 거래 서류를 찾을 수 없습니다." })).toBeVisible()
  await expect(page.getByRole("button", { name: "검토 완료 · 거래로 돌아가기", exact: true })).toHaveCount(0)
})
