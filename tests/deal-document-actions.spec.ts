import { expect, test, type Page } from "@playwright/test"

const source = "DL-260708-01"
const target = "DL-260707-04"
const storageKey = "ecoya-preview-deal-documents-v1"
async function openDocuments(page: Page, id = source) {
  await page.goto(`/erp/deals/${id}`)
  await page.getByRole("button", { name: "문서와 같이 보며 수정", exact: true }).click()
  return page.locator("#deal-document-preview")
}
async function mockAdapter(page: Page, method: string, failures = 1) {
  await page.evaluate(async ({ method, failures }) => {
    const modulePath = performance.getEntriesByType("resource").map(entry => entry.name).find(url => url.includes("/trade-os/lib/prototype-backend.ts"))!
    const { prototypeBackend } = await import(/* @vite-ignore */ modulePath)
    const original = prototypeBackend.dealDocuments[method]
    prototypeBackend.dealDocuments[method] = async (...args: unknown[]) => {
      if (failures-- > 0) throw new Error("연결 오류로 변경하지 못했습니다.")
      return original(...args)
    }
  }, { method, failures })
}

test("move requires target, impact and reason; failure preserves input and retry moves one document in both Deals", async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  const panel = await openDocuments(page)
  await panel.getByRole("button", { name: "발주서 문서 작업" }).click()
  await page.getByRole("menuitem", { name: "다른 거래로 이동" }).click()
  const dialog = page.getByRole("dialog", { name: "다른 거래로 이동", exact: true })
  const submit = dialog.getByRole("button", { name: "서류 이동", exact: true })
  await expect(submit).toBeDisabled()
  await dialog.getByRole("radio", { name: /ACME 7월 해상운송 계약/ }).check()
  await expect(dialog.locator('[aria-label="이동 영향"]')).toContainText("6 → 5건")
  await expect(submit).toBeDisabled()
  await dialog.getByLabel("이동 사유", { exact: true }).fill("잘못 연결한 서류를 담당 거래로 이동")
  await mockAdapter(page, "move")
  await submit.click()
  await expect(dialog.getByRole("alert")).toHaveText("연결 오류로 변경하지 못했습니다.")
  await expect(dialog.getByLabel("이동 사유", { exact: true })).toHaveValue("잘못 연결한 서류를 담당 거래로 이동")
  await expect(dialog.getByRole("radio", { name: /ACME 7월 해상운송 계약/ })).toBeChecked()
  expect(await page.evaluate(key => localStorage.getItem(key), storageKey)).toBeNull()
  await submit.click()
  await expect(dialog).toBeHidden()
  await expect(panel.getByRole("button", { name: "발주서 미비", exact: true })).toBeVisible()
  const saved = await page.evaluate(key => JSON.parse(localStorage.getItem(key)!), storageKey)
  expect(saved.documents[`demo-trade-doc:${source}:PO`].dealId).toBe(target)
  expect(saved.history).toHaveLength(1)
  expect(saved.history[0].reason).toBe("잘못 연결한 서류를 담당 거래로 이동")
  const destination = await openDocuments(page, target)
  await destination.getByRole("button", { name: "기타 서류 4건", exact: true }).click()
  await expect(destination.getByRole("button", { name: /PO-260704-18.pdf/ })).toBeVisible()
  await openDocuments(page)
  await expect(panel.getByRole("button", { name: "발주서 미비", exact: true })).toBeVisible()
})

test("replacement cancel and invalid file keep original; valid PDF keeps IDs and enters review instead of moving", async ({ page }) => {
  const panel = await openDocuments(page)
  await panel.getByRole("button", { name: "발주서 문서 작업" }).click()
  await page.getByRole("menuitem", { name: "파일 교체" }).click()
  let dialog = page.getByRole("dialog", { name: "파일 교체", exact: true })
  await expect(dialog.getByRole("button", { name: "파일 교체", exact: true })).toBeDisabled()
  await dialog.getByRole("button", { name: "취소", exact: true }).click()
  expect(await page.evaluate(key => localStorage.getItem(key), storageKey)).toBeNull()
  await panel.getByRole("button", { name: "발주서 문서 작업" }).click()
  await page.getByRole("menuitem", { name: "파일 교체" }).click()
  dialog = page.getByRole("dialog", { name: "파일 교체", exact: true })
  await dialog.getByLabel("교체할 PDF 파일").setInputFiles({ name: "wrong.txt", mimeType: "text/plain", buffer: Buffer.from("not pdf") })
  await dialog.getByRole("button", { name: "파일 교체", exact: true }).click()
  await expect(dialog.getByRole("alert")).toContainText("PDF 파일")
  expect(await page.evaluate(key => localStorage.getItem(key), storageKey)).toBeNull()
  await dialog.getByLabel("교체할 PDF 파일").setInputFiles({ name: "updated-PO.pdf", mimeType: "application/pdf", buffer: Buffer.from("%PDF-1.4\n%%EOF") })
  await dialog.getByRole("button", { name: "파일 교체", exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(panel).toContainText("updated-PO.pdf")
  await expect(panel.getByTitle("updated-PO.pdf 원본 PDF")).toBeVisible()
  await panel.getByRole("button", { name: "발주서 문서 작업" }).click()
  await expect(page.getByRole("menuitem", { name: "다른 거래로 이동" })).toHaveCount(0)
  const review = page.getByRole("menuitem", { name: "검토 화면 열기" })
  await expect(review).toHaveAttribute("href", new RegExp("demo-erp-doc.*PO/review.*from=deal.*tradeDocId=demo-trade-doc"))
  await review.click()
  await expect(page.getByRole("heading", { name: "문서 올리기", exact: true })).toBeVisible()
  await expect(page.getByTitle("updated-PO.pdf 원본 PDF")).toBeVisible()
  await expect(page.getByRole("link", { name: `${source} 거래로 돌아가기` })).toBeVisible()
  expect(new URL(page.url()).searchParams.get("tradeDocId")).toBe(`demo-trade-doc:${source}:PO`)
  const saved = await page.evaluate(key => JSON.parse(localStorage.getItem(key)!), storageKey)
  expect(saved.documents[`demo-trade-doc:${source}:PO`]).toMatchObject({ revision: 2, state: "needs_review", dealId: source })
})

test("type selection only appears for needs-type records and loads allowed options with read retry", async ({ page }) => {
  await page.goto(`/erp/deals/${source}`)
  await page.evaluate(({ key, source }) => {
    const id = `demo-trade-doc:${source}:QC`
    localStorage.setItem(key, JSON.stringify({ documents: { [id]: { id, erpDocumentId: `demo-erp-doc:${source}:QC`, originDealId: source, originCode: "QC", dealId: source, code: "UNK", type: "유형 미확인", file: "unclassified.pdf", state: "needs_type", revision: 1 } }, history: [] }))
  }, { key: storageKey, source })
  const panel = await openDocuments(page)
  await panel.getByRole("button", { name: "기타 서류 3건", exact: true }).click()
  await panel.getByRole("button", { name: /unclassified.pdf/ }).click()
  await panel.getByRole("button", { name: "유형 미확인 문서 작업" }).click()
  await expect(page.getByRole("menuitem", { name: "다른 거래로 이동" })).toHaveCount(0)
  await expect(page.getByRole("menuitem", { name: "검토 화면 열기" })).toHaveCount(0)
  await mockAdapter(page, "listTypes")
  await page.getByRole("menuitem", { name: "문서 유형 선택" }).click()
  const dialog = page.getByRole("dialog", { name: "문서 유형 선택", exact: true })
  await expect(dialog.getByRole("alert")).toContainText("불러오지 못했습니다")
  await expect(dialog.getByRole("button", { name: "유형 저장" })).toBeDisabled()
  await dialog.getByRole("button", { name: "다시 확인" }).click()
  await dialog.getByRole("combobox", { name: "문서 유형", exact: true }).click()
  await page.getByRole("option", { name: "검사성적서", exact: true }).click()
  await dialog.getByRole("button", { name: "유형 저장" }).click()
  await expect(dialog).toBeHidden()
  await panel.getByRole("button", { name: "검사성적서 문서 작업" }).click()
  await expect(page.getByRole("menuitem", { name: "문서 유형 선택" })).toHaveCount(0)
  await expect(page.getByRole("menuitem", { name: "검토 화면 열기" })).toBeVisible()
})

