import { test, expect } from '@playwright/test'
for (const width of [1440,390]) test(`counterparty layout and actions ${width}`, async ({page}) => {
 await page.setViewportSize({width,height:1000})
 await page.goto('/erp/counterparties/ACME%20GmbH')
 await expect(page.getByRole('heading',{name:'ACME GmbH 매출처'})).toBeVisible()
 await expect(page.getByRole('button',{name:'외 1개 통화'})).toHaveCount(4)
 await page.getByRole('button',{name:'외 1개 통화'}).first().click()
 await expect(page.getByRole('region',{name:'받을 돈',exact:true})).toContainText('KRW')
 await page.getByRole('button',{name:'관련 거래 보기',exact:true}).click()
 await expect(page.locator('#counterparty-deals')).toBeInViewport()
 await expect(page.locator('#counterparty-deals')).toContainText('ETA')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
 await page.screenshot({path:`/tmp/counterparty-${width}.png`})
 await page.getByRole('button',{name:'정산으로 돌아가기'}).click()
 await expect(page).toHaveURL(/settlement/)
})
